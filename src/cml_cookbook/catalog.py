"""The generated catalog: index.yaml plus the recipe tables in the READMEs."""

from __future__ import annotations

import os
from pathlib import Path
from typing import Any

import yaml

from cml_cookbook.recipes import CATEGORIES, Recipe

INDEX_HEADER = "# Generated by `cookbook index`. Do not edit by hand.\n"
START = "<!-- catalog:start -->"
END = "<!-- catalog:end -->"


class CatalogError(Exception):
    pass


def _sorted(recipes: list[Recipe]) -> list[Recipe]:
    order = list(CATEGORIES)
    return sorted(recipes, key=lambda r: (order.index(r.category), r.id))


def recipe_entry(recipe: Recipe, root: Path) -> dict[str, Any]:
    data = recipe.data
    requirements = data["requirements"]
    runs = sorted(data["tested_on"], key=lambda run: run["date"])
    last = runs[-1] if runs else None
    return {
        "id": recipe.id,
        "title": data["title"],
        "category": recipe.category,
        "path": recipe.path.relative_to(root).as_posix(),
        "version": recipe.version,
        "status": data["status"],
        "replaced_by": data.get("replaced_by"),
        "level": data.get("level"),
        "summary": " ".join(data["summary"].split()),
        "tags": list(data.get("tags", [])),
        "nodes": recipe.licensed_node_count(),
        "license_tier": recipe.license_tier(),
        "ram_mb": requirements.get("ram_mb"),
        "cml_min_version": requirements["cml_min_version"],
        "node_definitions": sorted({node["node_definition"] for node in recipe.nodes}),
        "refplat_only": all(image["refplat"] for image in requirements["images"]),
        "external": [system["name"] for system in requirements.get("external", [])],
        "inputs": [item["name"] for item in data.get("inputs", [])],
        "last_tested": (
            {key: last[key] for key in ("recipe_version", "cml_version", "date", "result")} if last else None
        ),
    }


def build_index(recipes: list[Recipe], root: Path) -> str:
    index = {"schema_version": 1, "recipes": [recipe_entry(r, root) for r in _sorted(recipes)]}
    return INDEX_HEADER + yaml.safe_dump(index, sort_keys=False, allow_unicode=True, width=100)


def recipe_table(recipes: list[Recipe], relative_to: Path) -> str:
    if not recipes:
        return "_No recipes yet._"
    rows = [
        "| Recipe | What it builds | Nodes | Tier | Status | Version |",
        "|---|---|---|---|---|---|",
    ]
    for recipe in _sorted(recipes):
        link = Path(os.path.relpath(recipe.path, relative_to)).as_posix()
        summary = " ".join(recipe.data["summary"].split()).replace("|", "\\|")
        rows.append(
            f"| [{recipe.data['title']}]({link}/) | {summary} | {recipe.licensed_node_count()} "
            f"| {recipe.license_tier()} | {recipe.data['status']} | {recipe.version} |"
        )
    return "\n".join(rows)


def root_catalog(recipes: list[Recipe], root: Path) -> str:
    sections = []
    for category, title in CATEGORIES.items():
        members = [r for r in recipes if r.category == category]
        sections.append(f"### [{title}](recipes/{category}/)\n\n{recipe_table(members, root)}")
    return "\n\n".join(sections)


def replace_block(text: str, content: str, where: str) -> str:
    start = text.find(START)
    end = text.find(END)
    if start == -1 or end == -1 or end < start:
        raise CatalogError(f"{where}: needs a {START} ... {END} block for the catalog")
    return text[:start] + f"{START}\n\n{content}\n\n{END}" + text[end + len(END) :]


def catalog_files(recipes: list[Recipe], root: Path) -> dict[Path, str]:
    """Every generated file mapped to the content it should have."""
    files: dict[Path, str] = {root / "index.yaml": build_index(recipes, root)}

    readme = root / "README.md"
    if not readme.is_file():
        raise CatalogError("README.md is missing")
    files[readme] = replace_block(readme.read_text(encoding="utf-8"), root_catalog(recipes, root), "README.md")

    for category in CATEGORIES:
        category_dir = root / "recipes" / category
        category_readme = category_dir / "README.md"
        if not category_readme.is_file():
            raise CatalogError(f"recipes/{category}/README.md is missing")
        members = [r for r in recipes if r.category == category]
        files[category_readme] = replace_block(
            category_readme.read_text(encoding="utf-8"),
            recipe_table(members, category_dir),
            f"recipes/{category}/README.md",
        )
    return files


def write_catalog(recipes: list[Recipe], root: Path, check: bool = False) -> list[Path]:
    """Write the catalog, or with `check` only report which files are out of date."""
    stale = []
    for path, content in catalog_files(recipes, root).items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != content:
            stale.append(path)
            if not check:
                path.write_text(content, encoding="utf-8")
    return stale
